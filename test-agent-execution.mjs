import fs from "node:fs";
import http from "node:http";
import os from "node:os";
import path from "node:path";
import { spawn } from "node:child_process";

const tmp=fs.mkdtempSync(path.join(os.tmpdir(),"romcp-agent-exec-"));
process.env.STATE_FILE=path.join(tmp,"state.json");
process.env.AUTH_MODE="noauth";
process.env.TARGETS_FILE=path.resolve("config/targets.example.json");
const state=await import("./dist/state/store.js");
const gateway=await import("./dist/agent/gateway.js");
state.initStateStore();
const pair=state.createPairing({hostname:"exec-test-host",agent_version:"2.0.0-test"});
if(!state.approvePairingByCode(pair.code)) throw new Error("approval failed");
const claimed=state.claimPairing(pair.pairing_id,pair.poll_token);
if(claimed.status!=="paired") throw new Error("claim failed");
const server=http.createServer((_req,res)=>res.end("ok"));
gateway.attachAgentGateway(server);
await new Promise((resolve)=>server.listen(3121,"127.0.0.1",resolve));
const deviceState=path.join(tmp,"device.json");
fs.writeFileSync(deviceState,JSON.stringify({control_plane:"http://127.0.0.1:3121",device_id:claimed.device.device_id,device_token:claimed.device_token,paired_at:new Date().toISOString()}),{mode:0o600});
const child=spawn(process.execPath,["dist/agent/cli.js","run"],{cwd:process.cwd(),env:{...process.env,WANDORA_AGENT_STATE:deviceState},stdio:["ignore","pipe","pipe"]});
let logs="";
child.stdout.on("data",(d)=>logs+=d.toString());
child.stderr.on("data",(d)=>logs+=d.toString());
for(let i=0;i<50&&!logs.includes("AGENT_CHANNEL=WELCOME");i++) await new Promise(r=>setTimeout(r,100));
if(!logs.includes("AGENT_CHANNEL=WELCOME")) throw new Error("agent did not connect: "+logs);
const host=await gateway.dispatchAgentOperation(claimed.device.device_id,{op:"host.hostname"});
if(host.code!==0||!host.stdout.trim()) throw new Error("hostname op failed");
console.log("AGENT_EXEC_HOSTNAME=PASS");
const uptime=await gateway.dispatchAgentOperation(claimed.device.device_id,{op:"host.uptime_pretty"});
if(uptime.code!==0) throw new Error("uptime op failed");
console.log("AGENT_EXEC_UPTIME=PASS");
const denied=await gateway.dispatchAgentOperation(claimed.device.device_id,{op:"fs.read_head",args:{path:"../../etc/shadow",bytes:64}});
if(denied.code===0) throw new Error("invalid path was not denied");
console.log("AGENT_EXEC_PATH_GUARD=PASS");
state.revokeDevice(claimed.device.device_id);
gateway.disconnectAgentDevice(claimed.device.device_id);
await new Promise(r=>setTimeout(r,100));
child.kill("SIGTERM");
server.close();
fs.rmSync(tmp,{recursive:true,force:true});
console.log("AGENT_EXECUTION_V1=GREEN");